        sport_id = sport_map.get(sport_name)
        for group_name, name, load, desc, reps_light, reps_medium, reps_heavy in ex_list:
            group_id = get_group_id(sport_id, group_name)
            if not group_id:
                print(f"Группа '{group_name}' для спорта '{sport_name}' не найдена. Пропускаем упражнение '{name}'.")
