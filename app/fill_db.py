from database import get_connection


def fill_sports_and_exercises():
    conn = get_connection()
    cursor = conn.cursor()

    # Виды спорта
    sports = ['фитнес', 'пауэрлифтинг', 'тяжёлая атлетика', 'кроссфит']
    for sport in sports:
        cursor.execute("INSERT OR IGNORE INTO sports (name) VALUES (?)", (sport,))
    conn.commit()

    # Получаем id видов спорта
    cursor.execute("SELECT id, name FROM sports")
    sport_map = {row['name']: row['id'] for row in cursor.fetchall()}

    # Упражнения по видам спорта
    exercises = {
        'фитнес': [
            ('Приседания с собственным весом', 'лёгкий', 'Приседать без дополнительного веса'),
            ('Отжимания', 'средний', 'Отжимания от пола с правильной техникой'),
            ('Планка', 'средний', 'Статическое удержание тела в горизонтальном положении'),
            ('Берпи', 'тяжёлый', 'Комбинированное упражнение с прыжком и отжиманием'),
            ('Подъем ног в висе', 'тяжёлый', 'Упражнение на пресс в висе на турнике'),
        ],
        'пауэрлифтинг': [
            ('Приседания со штангой', 'средний', 'Приседания с весом на плечах'),
            ('Жим лёжа', 'средний', 'Жим штанги лёжа на скамье'),
            ('Становая тяга', 'тяжёлый', 'Подъем штанги с пола до выпрямления тела'),
            ('Жим штанги стоя', 'лёгкий', 'Жим штанги над головой стоя'),
            ('Тяга штанги в наклоне', 'тяжёлый', 'Тяга штанги к поясу в наклоне'),
        ],
        'тяжёлая атлетика': [
            ('Рывок штанги', 'тяжёлый', 'Взрывное поднятие штанги с пола в одну фазу'),
            ('Толчок штанги', 'тяжёлый', 'Подъем штанги над головой с груди'),
            ('Приседания со штангой', 'средний', 'Приседания с весом на плечах'),
            ('Тяга к рывковая', 'тяжёлый', 'Подъем штанги с пола'),
            ('Выпады с гантелями', 'лёгкий', 'Шаг вперед с гантелями в руках'),
        ],
        'кроссфит': [
            ('Тяга штанги в наклоне', 'средний', 'Тяга штанги к поясу в наклоне'),
            ('Бёрпи', 'тяжёлый', 'Комбинированное упражнение с прыжком и отжиманием'),
            ('Подтягивания', 'средний', 'Подтягивания на турнике'),
            ('Русские скручивания', 'лёгкий', 'Упражнение на пресс сидя с поворотами корпуса'),
            ('Медбол бросок', 'тяжёлый', 'Бросок медицинского мяча вперед'),
        ]
    }

    for sport_name, ex_list in exercises.items():
        sport_id = sport_map.get(sport_name)
        for name, load, description in ex_list:
            cursor.execute("""
                INSERT INTO exercises (name, sport_id, load_level, description)
                VALUES (?, ?, ?, ?)
            """, (name, sport_id, load, description))
    conn.commit()
    conn.close()
    print("Данные добавлены в базу.")

if __name__ == "__main__":
    fill_sports_and_exercises()
